// What the caption fitter knows about each caption font: how wide every letter is and how far
// each pair of letters pulls together (kerning). Data only; captionFit.ts turns it into a width.
//
// These numbers were not read off the font files with a script of ours. They were measured in
// Chromium, the engine whose ctx.measureText decides where the rasterizer wraps a caption
// (titleRaster.titleLayout), with each bundled font loaded the way titleFonts.ts registers it
// (same weight range), at 1000 px so one pixel is one font unit. Every character alone gave its
// advance, and every ordered pair of characters minus the two advances gave its kerning. Width is
// exactly linear in the font size (checked from 8 to 200 px: kerning is on at every size), so units per
// 1000 em times the size over 1000 is the width in pixels, at any size.
//
// Ligatures are measured the same way: Montserrat fuses fi and fl, Oswald ffi and ffl, and the
// fused glyph is narrower or wider than its letters side by side and kerns differently with its
// neighbours. Each is one extra character (a private use code point) in the tables below.
//
// Why kerning is here at all: a table of advances alone read "AWAKE DOESN'T REALLY" in Oswald as
// 961 px, over the 950 px line of a 1080 px frame, when it draws as 948.7 px and fits. Oswald pulls
// A-W, W-A and L-Y together by 124 units on that one line, so the fitter cut a caption that fits.
//
// Measured with the Chromium that Playwright 1.61.1 ships, on Windows 11, 2026-10-20. To redo it
// for a new or changed font, load the file with a FontFace, measure with an OffscreenCanvas 2d
// context, and rebuild the tables below. Letters the file does not have are drawn in the
// next face of the stack (Arial Black on Windows), and the numbers here are that face's for them.
//
// Kerning is stored as classes, because most letters kern alike: `left` lists the characters
// that act as the left letter of a pair, one string per class (class numbers start at 1),
// `right` the same for the right letter, and `pairs` is flat [leftClass, rightClass, units,
// ...]. A character in no class kerns with nothing.

/** Everything the fitter needs to width a line in one font. Units are per 1000 em. */
export interface FontMetrics {
  /** Advance of ' ' (32) to '~' (126). */
  readonly advance: readonly number[]
  /** Advance of a character past '~' whose width differs from its plain letter (the first letter of its NFD form). */
  readonly extra?: Readonly<Record<string, number>>
  /**
   * Letters the font fuses into one glyph (Montserrat fi and fl, Oswald ffi and ffl), each as the private use
   * character that stands for it in `extra` and `kern`. The glyph has its own width and kerns on its own.
   */
  readonly ligatures?: Readonly<Record<string, string>>
  /** Pair kerning: left and right classes of characters, and flat [left, right, units] triples. */
  readonly kern?: {
    readonly left: readonly string[]
    readonly right: readonly string[]
    readonly pairs: readonly number[]
  }
}

